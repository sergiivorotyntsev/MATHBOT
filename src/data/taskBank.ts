// Вспомогательная функция: получить задачи по уровню сложности
export const getTasksByDifficulty = (skill: SkillType, difficulty: number): Task[] => {
  return taskBank[skill].filter(task => task.d === difficulty);
};

// Вспомогательная функция: получить случайную задачу
export const getRandomTask = (skill: SkillType, maxDifficulty: number = 6): Task => {
  const available = taskBank[skill].filter(task => task.d <= maxDifficulty);
  return available[Math.floor(Math.random() * available.length)];
};

// Вспомогательная функция: получить задачи по теме
export const getTasksByTopic = (skill: SkillType, topic: string): Task[] => {
  return taskBank[skill].filter(task => task.t === topic);
};

