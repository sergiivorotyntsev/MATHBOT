// Функция для поиска гида по теме
export const getGuideByTopic = (topic: string): MethodologyGuide | undefined => {
  return methodologyGuides.find(guide => guide.topic === topic);
};

// Функция для получения всех тем определённого уровня
export const getGuidesByLevel = (level: string): MethodologyGuide[] => {
  return methodologyGuides.filter(guide => guide.level.includes(level));
};

// Функция для поиска связанных тем
export const getRelatedGuides = (topic: string): MethodologyGuide[] => {
  const guide = getGuideByTopic(topic);
  if (!guide) return [];

  return methodologyGuides.filter(g =>
    guide.relatedTopics.includes(g.topic)
  );
};

